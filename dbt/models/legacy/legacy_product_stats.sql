SELECT
  chain_id,
  chain_name,
  product_type,
  beefy_key,
  product_address,
  display_name,
  is_active,
  platform_id,
  date_hour,
  tvl_usd,
  apy,
  compoundings_per_year,
  fee_rate_performance AS beefy_performance_fee,
  fee_rate_lp AS lp_fee,
  apy AS total_apy,
  apr_vault AS vault_apr,
  apr_trading AS trading_apr,
  apr_clm AS clm_apr,
  apr_reward_pool AS reward_pool_apr,
  apr_reward_pool_trading AS reward_pool_trading_apr,
  apy_vault AS vault_apy,
  apr_liquid_staking AS liquid_staking_apr,
  apr_composable_pool AS composable_pool_apr,
  apr_merkl AS merkl_apr,
  apr_linea_ignition AS linea_ignition_apr,
  want_price_usd AS lp_price,
  want_tokens AS breakdown_tokens,
  want_balances AS breakdown_balances,
  want_total_supply AS total_supply,
  clm_pool_liquidity AS underlying_liquidity,
  clm_pool_balances AS underlying_balances,
  clm_pool_liquidity_price_usd AS underlying_price,
  harvest_amount AS underlying_amount_compounded,
  harvest_amount_usd / nullIf(toFloat64(harvest_amount), 0) AS underlying_token_price_usd,
  harvest_amount_usd AS underlying_amount_compounded_usd,
  harvest_call_fee,
  harvest_call_fee_usd,
  harvest_gas_fee AS gas_fee,
  harvest_gas_fee_usd AS gas_fee_usd,
  harvest_platform_fee AS platform_fee,
  harvest_platform_fee_usd AS platform_fee_usd,
  harvest_strategist_fee AS strategist_fee,
  harvest_strategist_fee_usd AS strategist_fee_usd,
  harvest_amount,
  harvest_amount_usd,
  harvest_native_price_usd AS avg_native_price,
  harvest_count AS harvest_txn_count,
  if(harvest_count IS NULL, NULL, toUInt8(1)) AS harvest_vault_count,
  share_price_usd AS share_token_price_usd
FROM {{ ref('fact_product_stats_1h') }}
